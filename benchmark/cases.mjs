/**
 * The benchmark cases.
 *
 * Each one builds a real .xlsx in memory, then answers the same question twice:
 * the way an agent writes it from memory (`naive`), and the way this skill
 * teaches (`skilled`). Both are compared against an answer computed from the
 * data, never hardcoded by hand.
 *
 * Deterministic, offline, free: no LLM, no network, no fixtures on disk. A
 * benchmark you can only afford to run monthly stops catching regressions.
 */
import ExcelJS from "exceljs";
import { readTable, cellValue, asNumber } from "../skills/excel-ops/scripts/read-table.mjs";

/** Round-trip a built workbook through the xlsx writer so we test the READ path. */
async function roundTrip(build) {
    const wb = new ExcelJS.Workbook();
    wb.created = new Date(0);
    build(wb);
    const buf = await wb.xlsx.writeBuffer();
    const read = new ExcelJS.Workbook();
    await read.xlsx.load(buf);
    return read;
}

const sum = (xs) => xs.reduce((a, b) => a + b, 0);

export const CASES = [
    {
        name: "header-not-on-row-1",
        trap: "Reports open with a title and blank rows. Row 1 is not the header.",
        expected: 3350,
        build(wb) {
            const ws = wb.addWorksheet("S");
            ws.getCell("A1").value = "Quarterly Revenue";
            ws.getCell("A2").value = "Generated by Finance";
            ws.getCell("A4").value = "Region";
            ws.getCell("B4").value = "Amount";
            [["North", 1200], ["South", 950], ["East", 1200]].forEach(([r, a], i) => {
                ws.getCell(`A${5 + i}`).value = r;
                ws.getCell(`B${5 + i}`).value = a;
            });
        },
        naive(wb) {
            // Headers from row 1, objects from row 2 — the standard recipe.
            const ws = wb.worksheets[0];
            const headers = [];
            ws.getRow(1).eachCell((c, i) => (headers[i] = String(c.value)));
            let total = 0;
            for (let n = 2; n <= ws.rowCount; n++) {
                const obj = {};
                ws.getRow(n).eachCell((c, i) => (obj[headers[i]] = c.value));
                total += obj.Amount ?? 0;
            }
            return total;
        },
        skilled(wb) {
            const { rows } = readTable(wb.worksheets[0]);
            return sum(rows.map((r) => r.Amount));
        },
    },

    {
        name: "numbers-stored-as-text",
        trap: 'Exported sheets ship "1,234.50" as a string. `+=` concatenates instead of adding.',
        expected: 2184.5,
        build(wb) {
            const ws = wb.addWorksheet("S");
            ws.getCell("A1").value = "Item";
            ws.getCell("B1").value = "Amount";
            [["a", " 1,234.50 "], ["b", "$950.00"], ["c", "(0.00)"]].forEach(([i, a], n) => {
                ws.getCell(`A${2 + n}`).value = i;
                ws.getCell(`B${2 + n}`).value = a;
            });
        },
        naive(wb) {
            const ws = wb.worksheets[0];
            let total = 0;
            for (let n = 2; n <= ws.rowCount; n++) total += ws.getRow(n).getCell(2).value;
            return total;
        },
        skilled(wb) {
            const { rows } = readTable(wb.worksheets[0]);
            return sum(rows.map((r) => asNumber(r.Amount) ?? 0));
        },
    },

    {
        name: "formula-cells",
        trap: "A formula cell's value is {formula, result}. Reading `.value` gives you an object.",
        expected: 60,
        build(wb) {
            const ws = wb.addWorksheet("S");
            ws.getCell("A1").value = "Item";
            ws.getCell("B1").value = "Amount";
            [10, 20, 30].forEach((v, i) => {
                ws.getCell(`A${2 + i}`).value = `row${i}`;
                ws.getCell(`B${2 + i}`).value = { formula: `${v}*1`, result: v };
            });
        },
        naive(wb) {
            const ws = wb.worksheets[0];
            let total = 0;
            for (let n = 2; n <= ws.rowCount; n++) {
                const v = ws.getRow(n).getCell(2).value;
                total += typeof v === "number" ? v : Number(v) || 0;
            }
            return total;
        },
        skilled(wb) {
            const { rows } = readTable(wb.worksheets[0]);
            return sum(rows.map((r) => r.Amount));
        },
    },

    {
        name: "date-timezone",
        trap: "`cell.text` renders a date in the machine's LOCAL zone — a UTC midnight slips to the previous day west of Greenwich.",
        expected: "2026-01-15",
        build(wb) {
            const ws = wb.addWorksheet("S");
            ws.getCell("A1").value = "Item";
            ws.getCell("B1").value = "Due";
            ws.getCell("A2").value = "invoice";
            ws.getCell("B2").value = new Date(Date.UTC(2026, 0, 15));
        },
        naive(wb) {
            // Formatting a Date from its LOCAL parts — what every date-to-string
            // helper does unless you stop it.
            const d = new Date(wb.worksheets[0].getCell("B2").text);
            const pad = (n) => String(n).padStart(2, "0");
            return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
        },
        skilled(wb) {
            const v = cellValue(wb.worksheets[0].getCell("B2"));
            return v.toISOString().slice(0, 10);
        },
    },

    {
        name: "sparse-and-phantom-rows",
        trap: "`rowCount` counts rows that only carry formatting, and `eachRow` skips blanks — so a running counter never matches the real row number.",
        expected: 3,
        build(wb) {
            const ws = wb.addWorksheet("S");
            ws.getCell("A1").value = "Item";
            ws.getCell("B1").value = "Amount";
            ws.getCell("A2").value = "a";
            ws.getCell("B2").value = 1;
            ws.getCell("A3").value = "b";
            ws.getCell("B3").value = 2;
            ws.getCell("A4").value = "c";
            ws.getCell("B4").value = 3;
            // Formatting-only rows below the data: real files are full of these.
            for (const n of [5, 6, 7, 8]) ws.getRow(n).getCell(2).numFmt = "#,##0";
        },
        naive(wb) {
            const ws = wb.worksheets[0];
            let count = 0;
            for (let n = 2; n <= ws.rowCount; n++) count++;
            return count;
        },
        skilled(wb) {
            return readTable(wb.worksheets[0]).rows.length;
        },
    },

    {
        name: "duplicate-headers",
        trap: 'Two columns called "Amount" collapse into one key — the first is silently lost.',
        expected: 30,
        build(wb) {
            const ws = wb.addWorksheet("S");
            ws.getCell("A1").value = "Item";
            ws.getCell("B1").value = "Amount";
            ws.getCell("C1").value = "Amount";
            ws.getCell("A2").value = "a";
            ws.getCell("B2").value = 10;
            ws.getCell("C2").value = 20;
        },
        naive(wb) {
            const ws = wb.worksheets[0];
            const headers = [];
            ws.getRow(1).eachCell((c, i) => (headers[i] = String(c.value)));
            const obj = {};
            ws.getRow(2).eachCell((c, i) => (obj[headers[i]] = c.value));
            return Object.values(obj).filter((v) => typeof v === "number").reduce((a, b) => a + b, 0);
        },
        skilled(wb) {
            const { rows } = readTable(wb.worksheets[0]);
            return sum(Object.values(rows[0]).filter((v) => typeof v === "number"));
        },
    },

    {
        name: "rich-text-and-hyperlinks",
        trap: "Styled or linked cells hold objects, so string work yields [object Object].",
        expected: "Acme Corp|invoices",
        build(wb) {
            const ws = wb.addWorksheet("S");
            ws.getCell("A1").value = "Client";
            ws.getCell("B1").value = "Folder";
            ws.getCell("A2").value = { richText: [{ text: "Acme " }, { text: "Corp", font: { bold: true } }] };
            ws.getCell("B2").value = { text: "invoices", hyperlink: "https://example.com/invoices" };
        },
        naive(wb) {
            const ws = wb.worksheets[0];
            return `${ws.getCell("A2").value}|${ws.getCell("B2").value}`;
        },
        skilled(wb) {
            const { rows } = readTable(wb.worksheets[0]);
            return `${rows[0].Client}|${rows[0].Folder}`;
        },
    },

    {
        name: "merged-title-above-headers",
        trap: "A merged banner spreads its text across columns, so the widest row is not the header row.",
        expected: ["Region", "Amount", "Owner"],
        build(wb) {
            const ws = wb.addWorksheet("S");
            ws.getCell("A1").value = "CONFIDENTIAL — INTERNAL ONLY";
            ws.mergeCells("A1:E1");
            ws.getCell("A2").value = "Region";
            ws.getCell("B2").value = "Amount";
            ws.getCell("C2").value = "Owner";
            ws.getCell("A3").value = "North";
            ws.getCell("B3").value = 1;
            ws.getCell("C3").value = "ana";
        },
        naive(wb) {
            const ws = wb.worksheets[0];
            const out = [];
            ws.getRow(1).eachCell((c) => out.push(String(c.value)));
            return out;
        },
        skilled(wb) {
            return readTable(wb.worksheets[0]).headers;
        },
    },

    {
        name: "second-sheet-is-the-data",
        trap: "Sheet 1 is a cover page. Defaulting to `worksheets[0]` reads the wrong sheet and reports zero.",
        expected: 500,
        build(wb) {
            const cover = wb.addWorksheet("Cover");
            cover.getCell("A1").value = "Monthly pack";
            const ws = wb.addWorksheet("Data");
            ws.getCell("A1").value = "Item";
            ws.getCell("B1").value = "Amount";
            ws.getCell("A2").value = "a";
            ws.getCell("B2").value = 500;
        },
        naive(wb) {
            const ws = wb.worksheets[0];
            let total = 0;
            for (let n = 2; n <= ws.rowCount; n++) {
                const v = ws.getRow(n).getCell(2).value;
                if (typeof v === "number") total += v;
            }
            return total;
        },
        skilled(wb) {
            // Pick the sheet that actually holds the columns you need.
            const ws =
                wb.worksheets.find((s) => {
                    try {
                        return readTable(s, { expect: ["Amount"] }).rows.length > 0;
                    } catch {
                        return false;
                    }
                }) ?? wb.worksheets[0];
            return sum(readTable(ws).rows.map((r) => r.Amount));
        },
    },
];

/** Build every case's workbook once. */
export async function buildAll() {
    const out = [];
    for (const c of CASES) out.push({ ...c, wb: await roundTrip(c.build) });
    return out;
}
